import type { Row } from '../types';

export interface Sequence {
  name: string;
  numBells: number;
  /**
   * Each step is an array of one or more allowed rows.
   * Index 0 is the starting position. A call is correct if the
   * resulting row matches ANY of the allowed rows at the next step.
   * Steps with multiple entries accommodate alternative paths to the
   * same point in the sequence.
   */
  rows: Row[][];
}

